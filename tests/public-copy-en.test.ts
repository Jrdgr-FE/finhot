import {stub,tag} from './setup.ts';
import assert from 'node:assert/strict';
import {after,before,test} from 'node:test';
import {sql,closeDb} from '@aihot/backend/db';
import {upsertMaterial} from '@aihot/backend/content/materials';
import {publishArticle} from '@aihot/backend/publication/publish';
import {edgeSnapshot} from '@aihot/backend/publication/edge';
import {translatePublicCopy,validEnglishCopy} from '@aihot/backend/editorial/public-copy-en';
import {stopBoss} from '@aihot/backend/jobs/queue';
import {localizeItem} from '@aihot/backend/publication/localized';
const T=tag();let id:string;
const provider=await stub((_hit,req)=>{const body=JSON.parse(req.body);assert.ok(body.max_tokens<=7000,'translation has a bounded token reserve');const rows=JSON.parse(body.messages.at(-1).content);return {choices:[{message:{content:JSON.stringify({items:rows.map((r:any)=>({id:r.id,title:'Company reports revenue growth',summary:r.summary?'Revenue grew by 30%.':''}))})}}],usage:{prompt_tokens:10,completion_tokens:20}};});
process.env.FINHOT_PUBLIC_EN_ENABLED='true';process.env.TRANSLATE_MODEL='default';process.env.LLM_REASONING_HEADROOM='12000';Object.assign(process.env,{LLM_BASE_URL:provider.url+'/v1',LLM_API_KEY:'test',LLM_MODEL:'english-test'});
before(async()=>{
 await sql`INSERT INTO sources(id,name,kind,tier,participation_mode) VALUES('cninfo-company','公告','rss','T1','editorial') ON CONFLICT(id) DO UPDATE SET enabled=true`;
 // Isolate candidates from earlier files in the shared test database.
 await sql`UPDATE publications SET visibility='withdrawn'`;
 const r=await upsertMaterial({sourceId:'cninfo-company',url:'https://example.com/en-'+T,title:'公司营收增长',excerpt:'公开材料',via:'import'});id=r.articleId;await publishArticle(id);
 await sql`UPDATE publications SET visibility='public',title='公司营收增长',summary='营收增长30%。',selected=false WHERE article_id=${id}`;
});
after(async()=>{delete process.env.FINHOT_PUBLIC_EN_ENABLED;delete process.env.LLM_REASONING_HEADROOM;await provider.close();await stopBoss();await closeDb();});
test('English copy is cached, exported only for matching public text and never generated by a read',async()=>{
 assert.equal((await translatePublicCopy({maxBatches:1,priorityIds:[id]})).done,1);
 const reads=provider.hits();let snap=await edgeSnapshot();let item=snap.items.find((i:any)=>i.id===id);assert.equal(item.title_en,'Company reports revenue growth');assert.equal(item.summary_en,'Revenue grew by 30%.');
 assert.equal(localizeItem(item).title,'Company reports revenue growth');assert.equal(localizeItem(item,'zh-CN').title,'公司营收增长');
 assert.equal((await translatePublicCopy({maxBatches:1})).done,0);assert.equal(provider.hits(),reads);
 await sql`UPDATE publications SET summary='营收增长40%。' WHERE article_id=${id}`;
 item=(await edgeSnapshot()).items.find((i:any)=>i.id===id);assert.equal(item.title_en,null);assert.equal(item.summary_en,null);assert.equal(provider.hits(),reads);
 await sql`UPDATE publications SET visibility='withdrawn' WHERE article_id=${id}`;snap=await edgeSnapshot();assert.ok(!snap.items.some((i:any)=>i.id===id));
});
test('English fallback never invents a summary or leaks Chinese into English cards',()=>{
 const input={id:'a',title:'标题',summary:''};assert.equal(validEnglishCopy(input,{id:'a',title:'Headline',summary:'Invented'}),false);
 assert.equal(validEnglishCopy(input,{id:'a',title:'中文',summary:''}),false);assert.equal(validEnglishCopy(input,{id:'different',title:'Headline',summary:''}),false);
 const item={...input,source_id:'cninfo-company',source_name:'巨潮资讯'};
 const en=localizeItem(item);assert.equal(en.title,'English translation pending');assert.equal(en.summary,'');assert.equal(en.translation_pending,true);assert.ok(!/[\u3400-\u9fff]/.test(en.source_name));
 assert.equal(localizeItem({...item,original_title:'Original English headline'}).title,'Original English headline');
});

test('Paid English translation is off by default and does not call a provider',async()=>{
 delete process.env.FINHOT_PUBLIC_EN_ENABLED;const calls=provider.hits();
 assert.deepEqual(await translatePublicCopy(),{done:0,stopped:'disabled'});assert.equal(provider.hits(),calls);
});
